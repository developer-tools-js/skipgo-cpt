create function public.add_skip(p_no int, p_size int, p_yard text) returns void
language plpgsql security definer set search_path = public as $$
begin
  perform public.need('office');
  if exists (select 1 from public.skips where no = p_no) then raise exception 'Skip % already exists.', p_no; end if;
  insert into public.skips (no, size, yard) values (p_no, p_size, p_yard);
  insert into public.log (type, skip, yard, by_name) values ('add', p_no, p_yard, public.my_name());
end $$;

