-- SkipGo database setup.
-- Run this ONCE in Supabase: SQL Editor > New query > paste everything > Run.
-- It creates the tables, the security rules, and the actions the site is allowed to perform.
-- No prices or invoice amounts are stored here: prices live in the OneDrive price list and invoices are filed as PDFs in OneDrive.

-- ---------- Tables ----------
create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null unique,
  name text not null,
  role text not null default 'pending' check (role in ('pending','driver','office')),
  created_at timestamptz not null default now()
);

create table public.yards (
  name text primary key,
  lat double precision,
  lng double precision
);

create table public.settings (
  id int primary key default 1 check (id = 1),
  biz text not null default 'Your Skip Company (Pty) Ltd',
  vat boolean not null default true,
  next_inv int not null default 9372
);

create table public.skips (
  no int primary key check (no > 0),
  size int not null default 2 check (size in (2,3)),
  status text not null default 'yard' check (status in ('yard','client','service')),
  yard text references public.yards(name) on update cascade,
  note text not null default '',
  job jsonb
);

create table public.clients (
  id bigint generated by default as identity primary key,
  name text not null,
  contact text not null default '',
  phone text not null default '',
  email text not null default '',
  address text not null default '',
  area text not null default '',
  lat double precision,
  lng double precision,
  waste text not null default '',
  size text not null default '',          -- usual skip size(s)
  payment text not null default '',       -- EFT or COD (never an amount)
  handled_by text not null default '',    -- e.g. Gareth, as on the old client cards
  sla boolean not null default false,
  sla_days text not null default '',
  notes text not null default '',
  legacy jsonb,
  created_at timestamptz not null default now()
);
create index clients_name_idx on public.clients (lower(name));

-- Office-only notes about a client (drivers cannot read these).
create table public.client_private (
  client_id bigint primary key references public.clients(id) on delete cascade,
  office_notes text not null default ''
);

-- The schedule. Every drop-off, pick-up and swap is a job on a day.
create table public.jobs (
  id bigint generated by default as identity primary key,
  date date not null,
  run int not null default 1 check (run in (1,2)),   -- which of the two columns it shows in on the calendar
  pos int not null default 0,
  type text not null default 'drop' check (type in ('drop','pick','swap','other')),
  status text not null default 'planned' check (status in ('planned','done','cancelled')),
  driver text not null default '',
  client_id bigint references public.clients(id) on delete set null,
  client text not null default '',
  area text not null default '',
  area_code text not null default '',
  address text not null default '',
  lat double precision,
  lng double precision,
  waste text not null default 'Mixed',
  days int not null default 3,
  skip int,                                   -- the skip to collect, for pick-ups and swaps
  drop_skips int[] not null default '{}',     -- skips actually delivered
  pick_skips int[] not null default '{}',     -- skips actually collected
  note text not null default '',
  moved_from date,
  moves int not null default 0,
  invoice int,                                -- invoice number only; the invoice itself is a PDF in OneDrive
  done_at timestamptz,
  by_name text,
  source text not null default 'app' check (source in ('app','spreadsheet')),
  created_at timestamptz not null default now()
);
create index jobs_date_idx on public.jobs (date);
create index jobs_planned_idx on public.jobs (status) where status = 'planned';
create index jobs_drop_idx on public.jobs using gin (drop_skips);
create index jobs_pick_idx on public.jobs using gin (pick_skips);

create table public.log (
  id bigint generated always as identity primary key,
  t timestamptz not null default now(),
  type text not null,
  skip int not null,
  client text,
  area text,
  yard text,
  by_name text
);

-- ---------- Who is asking ----------
create function public.my_role() returns text
language sql stable security definer set search_path = public as
$$ select role from public.profiles where id = auth.uid() $$;

create function public.my_name() returns text
language sql stable security definer set search_path = public as
$$ select name from public.profiles where id = auth.uid() $$;

create function public.need(variadic roles text[]) returns void
language plpgsql stable security definer set search_path = public as $$
begin
  if public.my_role() is null or not (public.my_role() = any(roles)) then
    raise exception 'You do not have permission to do this.';
  end if;
end $$;

create function public.metres(lat1 double precision, lng1 double precision, lat2 double precision, lng2 double precision)
returns double precision language sql immutable as $$
  select 6371000 * 2 * asin(sqrt(
    power(sin(radians(lat2 - lat1) / 2), 2) +
    cos(radians(lat1)) * cos(radians(lat2)) * power(sin(radians(lng2 - lng1) / 2), 2)))
$$;

create function public.today() returns date language sql stable as
$$ select (now() at time zone 'Africa/Johannesburg')::date $$;

