language plpgsql security definer set search_path = public as $$
begin
  perform public.need('office');
  if coalesce(trim(p_name), '') = '' then raise exception 'Give the yard a name.'; end if;
  insert into public.yards (name, lat, lng) values (trim(p_name), p_lat, p_lng) on conflict (name) do nothing;
end $$;

create function public.save_settings(p_biz text, p_vat boolean, p_next_inv int) returns void
language plpgsql security definer set search_path = public as $$
declare v_max int;
begin
  perform public.need('office');
  select coalesce(max(invoice), 0) into v_max from public.jobs;
  if p_next_inv <= v_max then
    raise exception 'The next invoice number must be higher than %, the last invoice already filed.', v_max;
  end if;
  update public.settings set biz = p_biz, vat = p_vat, next_inv = p_next_inv where id = 1;
end $$;

create function public.set_role(p_user uuid, p_role text) returns void
language plpgsql security definer set search_path = public as $$
begin
  perform public.need('office');
  if p_role not in ('pending', 'driver', 'office') then raise exception 'Unknown role.'; end if;
  update public.profiles set role = p_role where id = p_user;
  if not exists (select 1 from public.profiles where role = 'office') then
    raise exception 'There must always be at least one office user.';
  end if;
end $$;

