-- ---------- New logins ----------
-- The first person to create an account becomes the office user. Everyone after waits for approval.
create function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, username, name, role)
  values (
    new.id,
    coalesce(nullif(new.raw_user_meta_data->>'username', ''), split_part(new.email, '@', 1)),
    coalesce(nullif(new.raw_user_meta_data->>'name', ''), split_part(new.email, '@', 1)),
    case when exists (select 1 from public.profiles where role = 'office') then 'pending' else 'office' end
  );
  return new;
end $$;

create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

-- ---------- Clients ----------
create function public._client_for(p_name text, p_area text, p_address text) returns bigint
language plpgsql security definer set search_path = public as $$
declare v_id bigint;
begin
  select id into v_id from public.clients where lower(name) = lower(trim(p_name)) order by id limit 1;
  if v_id is null then
    insert into public.clients (name, area, address) values (trim(p_name), coalesce(trim(p_area), ''), coalesce(p_address, ''))
    returning id into v_id;
  end if;
  return v_id;
end $$;
revoke execute on function public._client_for(text, text, text) from public, anon, authenticated;

create function public.save_client(
  p_id bigint, p_name text, p_contact text, p_phone text, p_email text, p_address text, p_area text,
  p_waste text, p_sla boolean, p_sla_days text, p_notes text, p_office_notes text,
  p_lat double precision default null, p_lng double precision default null,
  p_size text default null, p_payment text default null, p_handled_by text default null)
returns bigint language plpgsql security definer set search_path = public as $$
declare v_id bigint := p_id;
begin
  perform public.need('office');
  if coalesce(trim(p_name), '') = '' then raise exception 'Give the client a name.'; end if;
  if v_id is null then
    insert into public.clients (name) values (trim(p_name)) returning id into v_id;
  end if;
  update public.clients set name = trim(p_name), contact = coalesce(p_contact, ''), phone = coalesce(p_phone, ''),
    email = coalesce(p_email, ''), address = coalesce(p_address, ''), area = coalesce(trim(p_area), ''),
    waste = coalesce(p_waste, ''), sla = coalesce(p_sla, false), sla_days = coalesce(p_sla_days, ''),
    notes = coalesce(p_notes, ''), lat = coalesce(p_lat, lat), lng = coalesce(p_lng, lng),
    size = coalesce(p_size, size), payment = coalesce(p_payment, payment), handled_by = coalesce(p_handled_by, handled_by)
  where id = v_id;
  if not found then raise exception 'That client no longer exists.'; end if;
  insert into public.client_private (client_id, office_notes) values (v_id, coalesce(p_office_notes, ''))
  on conflict (client_id) do update set office_notes = excluded.office_notes;
  return v_id;
end $$;

-- ---------- Schedule ----------
create function public.add_job(
  p_date date, p_run int, p_type text, p_client_id bigint, p_client text, p_area text, p_address text default '',
  p_lat double precision default null, p_lng double precision default null, p_waste text default 'Mixed', p_days int default 3,
  p_skip int default null, p_note text default '', p_driver text default '')
returns bigint language plpgsql security definer set search_path = public as $$
declare v_id bigint; v_client bigint := p_client_id;
begin
  perform public.need('office');
  if p_date is null then raise exception 'Choose a date.'; end if;
  if coalesce(trim(p_client), '') = '' then raise exception 'Choose a client.'; end if;
  if p_type in ('pick','swap') and p_skip is null then raise exception 'Choose the skip to collect.'; end if;
  if v_client is null and p_type <> 'other' then v_client := public._client_for(p_client, p_area, p_address); end if;
  insert into public.jobs (date, run, pos, type, driver, client_id, client, area, address, lat, lng, waste, days, skip, note, by_name)
  values (p_date, coalesce(p_run, 1),
    (select coalesce(max(pos), 0) + 1 from public.jobs where date = p_date and run = coalesce(p_run, 1)),
    p_type, coalesce(p_driver, ''), v_client, trim(p_client), coalesce(trim(p_area), ''), coalesce(p_address, ''), p_lat, p_lng,
    coalesce(p_waste, 'Mixed'), greatest(coalesce(p_days, 3), 1), p_skip, coalesce(p_note, ''), public.my_name())
  returning id into v_id;
  return v_id;
end $$;

-- Reschedule: drivers and office may move a job that is not done yet, and change its driver.
create function public.move_job(p_id bigint, p_date date, p_run int default null, p_driver text default null) returns void
language plpgsql security definer set search_path = public as $$
declare j public.jobs;
begin
  perform public.need('driver', 'office');
  select * into j from public.jobs where id = p_id for update;
  if not found or j.status <> 'planned' then raise exception 'Only a job that is not done yet can be moved.'; end if;
  if p_date is null then raise exception 'Choose a date.'; end if;
  update public.jobs set date = p_date, run = coalesce(p_run, run), driver = coalesce(p_driver, driver),
    moved_from = case when p_date <> j.date then coalesce(moved_from, j.date) else moved_from end,
    moves = moves + case when p_date <> j.date then 1 else 0 end,
    pos = (select coalesce(max(pos), 0) + 1 from public.jobs where date = p_date and run = coalesce(p_run, j.run))
  where id = p_id;
end $$;

create function public.cancel_job(p_id bigint) returns void
language plpgsql security definer set search_path = public as $$
begin
  perform public.need('office');
  update public.jobs set status = 'cancelled' where id = p_id and status = 'planned';
end $$;

create function public.finish_job(p_id bigint) returns void
language plpgsql security definer set search_path = public as $$
begin
  perform public.need('driver', 'office');
  update public.jobs set status = 'done', done_at = now(), by_name = public.my_name()
  where id = p_id and status = 'planned' and type = 'other';
  if not found then raise exception 'Record drop-offs and pick-ups with the Drop off or Pick up buttons.'; end if;
end $$;

-- ---------- Skip movements ----------
-- Internal: puts a skip out at a client and ticks off (or creates) the job.
create function public._drop(
  p_no int, p_client text, p_area text, p_address text, p_waste text, p_days int,
  p_lat double precision, p_lng double precision, p_pin text, p_job bigint)
returns void language plpgsql security definer set search_path = public as $$
declare
  s public.skips; j public.jobs; v_client bigint;
  v_lat double precision := p_lat; v_lng double precision := p_lng; v_pin text := p_pin;
  v_flag int; v_days int := greatest(coalesce(p_days, 3), 1); v_now timestamptz := now();
  v_driver text := case when public.my_role() = 'driver' then public.my_name() else '' end;
begin
  select * into s from public.skips where no = p_no for update;
  if not found or s.status <> 'yard' then raise exception 'Skip % is not available. Choose another skip.', p_no; end if;
  if coalesce(trim(p_client), '') = '' or coalesce(trim(p_area), '') = '' then raise exception 'Client and area are required.'; end if;
  if p_job is not null then
    select * into j from public.jobs where id = p_job for update;
    if not found or j.status <> 'planned' then raise exception 'That job is already done or cancelled.'; end if;
    v_client := j.client_id;
    if v_pin = 'gps' and j.lat is not null then
      v_flag := round(public.metres(v_lat, v_lng, j.lat, j.lng));
      if v_flag <= 500 then v_flag := null; end if;
    elsif v_pin is distinct from 'gps' and j.lat is not null then
      v_lat := j.lat; v_lng := j.lng; v_pin := 'address';
    end if;
  end if;
  if v_client is null then v_client := public._client_for(p_client, p_area, p_address); end if;
  if p_job is not null then
    update public.jobs set status = 'done', done_at = v_now, by_name = public.my_name(), client_id = v_client,
      drop_skips = drop_skips || p_no, driver = case when driver = '' then v_driver else driver end where id = p_job;
  else
    insert into public.jobs (date, run, type, status, driver, client_id, client, area, address, lat, lng, waste, days, drop_skips, done_at, by_name)
    values (public.today(), 1, 'drop', 'done', v_driver, v_client, trim(p_client), trim(p_area), coalesce(p_address, ''),
            v_lat, v_lng, coalesce(p_waste, 'Mixed'), v_days, array[p_no], v_now, public.my_name())
    returning id into p_job;
  end if;
  update public.skips set status = 'client', yard = null, job = jsonb_build_object(
    'client', trim(p_client), 'client_id', v_client, 'area', trim(p_area), 'address', coalesce(p_address, ''),
    'waste', coalesce(p_waste, 'Mixed'), 'days', v_days,
    'droppedAt', (extract(epoch from v_now) * 1000)::bigint,
    'dueAt', (extract(epoch from v_now + make_interval(days => v_days)) * 1000)::bigint,
    'by', public.my_name(), 'job', p_job, 'lat', v_lat, 'lng', v_lng, 'pin', v_pin, 'flag', v_flag)
  where no = p_no;
  insert into public.log (t, type, skip, client, area, by_name) values (v_now, 'drop', p_no, trim(p_client), trim(p_area), public.my_name());
end $$;
revoke execute on function public._drop(int, text, text, text, text, int, double precision, double precision, text, bigint) from public, anon, authenticated;

create function public.drop_skip(
  p_no int, p_client text, p_area text, p_address text default '', p_waste text default 'Mixed', p_days int default 3,
  p_lat double precision default null, p_lng double precision default null, p_pin text default null, p_job bigint default null)
returns void language plpgsql security definer set search_path = public as $$
begin
  perform public.need('driver', 'office');
  perform public._drop(p_no, p_client, p_area, p_address, p_waste, p_days, p_lat, p_lng, p_pin, p_job);
end $$;

create function public.pick_skip(
  p_no int, p_yard text, p_swap int default null,
  p_lat double precision default null, p_lng double precision default null, p_job bigint default null)
returns void language plpgsql security definer set search_path = public as $$
declare s public.skips; j jsonb; jb public.jobs; v_job bigint := p_job; v_now timestamptz := now();
  v_driver text := case when public.my_role() = 'driver' then public.my_name() else '' end;
begin
  perform public.need('driver', 'office');
  select * into s from public.skips where no = p_no for update;
  if not found or s.status <> 'client' then raise exception 'Skip % is not out at a client.', p_no; end if;
  if not exists (select 1 from public.yards where name = p_yard) then raise exception 'Choose the yard the skip went back to.'; end if;
  if p_swap = p_no then raise exception 'The replacement must be a different skip.'; end if;
  j := s.job;
  if v_job is not null then
    select * into jb from public.jobs where id = v_job for update;
    if not found or jb.status <> 'planned' then raise exception 'That job is already done or cancelled.'; end if;
    update public.jobs set pick_skips = pick_skips || p_no, status = 'done', done_at = v_now, by_name = public.my_name(),
      driver = case when driver = '' then v_driver else driver end,
      type = case when p_swap is not null then 'swap' else type end
    where id = v_job;
  else
    insert into public.jobs (date, run, type, status, driver, client_id, client, area, address, skip, pick_skips, done_at, by_name)
    values (public.today(), 1, case when p_swap is not null then 'swap' else 'pick' end, 'done', v_driver,
            (j->>'client_id')::bigint, coalesce(j->>'client', ''), coalesce(j->>'area', ''), coalesce(j->>'address', ''),
            p_no, array[p_no], v_now, public.my_name())
    returning id into v_job;
  end if;
  update public.skips set status = 'yard', yard = p_yard, job = null where no = p_no;
  insert into public.log (type, skip, client, yard, by_name) values ('pick', p_no, j->>'client', p_yard, public.my_name());
  if p_swap is not null then
    update public.jobs set status = 'planned' where id = v_job;
    perform public._drop(p_swap, j->>'client', j->>'area', j->>'address', j->>'waste', coalesce((j->>'days')::int, 3),
      coalesce(p_lat, (j->>'lat')::double precision), coalesce(p_lng, (j->>'lng')::double precision),
      case when p_lat is not null then 'gps' else j->>'pin' end, v_job);
  end if;
end $$;

-- Record that an invoice PDF was filed in OneDrive for a job. Only the number is kept.
create function public.file_invoice(p_job bigint, p_no int) returns int
language plpgsql security definer set search_path = public as $$
declare st public.settings;
begin
  perform public.need('office');
  select * into st from public.settings where id = 1 for update;
  if p_no <> st.next_inv then raise exception 'Invoice number % was just used by someone else. Close the invoice and make it again.', p_no; end if;
  update public.jobs set invoice = p_no where id = p_job and status = 'done' and invoice is null;
  if not found then raise exception 'That job already has an invoice, or is not done yet.'; end if;
  update public.settings set next_inv = next_inv + 1 where id = 1;
  return p_no;
end $$;

create function public.set_service(p_no int, p_on boolean) returns void
language plpgsql security definer set search_path = public as $$
declare s public.skips; v_yard text;
begin
  perform public.need('office');
  select * into s from public.skips where no = p_no for update;
  if not found then raise exception 'Skip % does not exist.', p_no; end if;
  if p_on then
    if s.status <> 'yard' then raise exception 'Only a skip standing in a yard can be taken out of service.'; end if;
    update public.skips set status = 'service', yard = null where no = p_no;
    insert into public.log (type, skip, by_name) values ('service', p_no, public.my_name());
  else
    if s.status <> 'service' then raise exception 'Skip % is not out of service.', p_no; end if;
    select name into v_yard from public.yards order by name limit 1;
    update public.skips set status = 'yard', yard = v_yard where no = p_no;
    insert into public.log (type, skip, yard, by_name) values ('back', p_no, v_yard, public.my_name());
  end if;
end $$;

